class TestIndependentEventGenerationAndSeparation:
    """Proves Requirements A, B, C, D, and I."""

    def test_independent_phase9_event_generation_and_storage(
        self, restricted_vault_zone: Zone
    ) -> None:
        """Requirement A & B & C: Generate two genuinely independent Phase 9 events."""
        with tempfile.TemporaryDirectory() as tmpdir:
            store = SQLiteEventStore(str(Path(tmpdir) / "events.db"))
            fence_engine = FenceEngine()
            dwell_engine = DwellEngine(default_max_dwell_s=30.0, default_std_dwell_s=10.0)

            subject_ref = "subject_alpha_99"
            t0_ns = 1_000_000_000

            # 1. Event #1: RESTRICTED_ZONE_INTRUSION independently generated by FenceEngine
            bbox = BoundingBox(x1=100, y1=100, x2=200, y2=200)
            fence_events = fence_engine.check_subject(
                subject_ref=subject_ref,
                bbox=bbox,
                camera_id="cam-01",
                timestamp_ns=t0_ns,
                source_resolution=(1000, 1000),
                zones=[restricted_vault_zone],
                confidence=0.95,
            )
            assert len(fence_events) == 1
            fence_ev = fence_events[0]
            assert fence_ev.event_type == "RESTRICTED_ZONE_INTRUSION"
            assert fence_ev.is_restricted_zone is True

            ev_record_1 = Event(
                event_id="ev_indep_fence_01",
                event_type=EventType.RESTRICTED_ZONE_INTRUSION,
                global_id=subject_ref,
                camera_id="cam-01",
                timestamp_ns=t0_ns,
                frame_id=10,
                confidence=0.95,
                explanation=fence_ev.explanation,
                zone_id="zone_vault",
                metadata=fence_engine.build_evidence_payload(fence_ev),
            )
            store.append(ev_record_1)

            # 2. Event #2: LOITERING_DETECTED independently generated by DwellEngine
            t1_ns = t0_ns + 100_000_000_000  # 100s later (exceeds 30s max dwell)
            dwell_engine.record_zone_presence(
                subject_ref=subject_ref,
                zone_id="zone_vault",
                camera_id="cam-01",
                timestamp_ns=t0_ns,
                confidence=0.92,
                zone=restricted_vault_zone,
            )
            dwell_ev = dwell_engine.record_zone_presence(
                subject_ref=subject_ref,
                zone_id="zone_vault",
                camera_id="cam-01",
                timestamp_ns=t1_ns,
                confidence=0.92,
                zone=restricted_vault_zone,
            )
            assert dwell_ev is not None
            assert dwell_ev.zone_dwell_sigma > 5.0

            ev_record_2 = Event(
                event_id="ev_indep_dwell_01",
                event_type=EventType.LOITERING_DETECTED,
                global_id=subject_ref,
                camera_id="cam-01",
                timestamp_ns=t1_ns,
                frame_id=3000,
                confidence=0.92,
                explanation=dwell_ev.explanation,
                zone_id="zone_vault",
                metadata=dwell_engine.build_evidence_payload(dwell_ev),
            )
            store.append(ev_record_2)

            # Verify in store: 2 distinct events with different event_ids and types
            queried = store.query_events()
            assert len(queried) == 2
            event_types = {e.event_type for e in queried}
            assert event_types == {
                EventType.RESTRICTED_ZONE_INTRUSION,
                EventType.LOITERING_DETECTED,
            }
            assert queried[0].event_id != queried[1].event_id

            store.close()

    def test_separate_evidence_records_no_field_stuffing(
        self, restricted_vault_zone: Zone
    ) -> None:
        """Requirement C & I: Separate Evidence records without field stuffing."""
        fence_engine = FenceEngine()
        dwell_engine = DwellEngine(default_max_dwell_s=30.0, default_std_dwell_s=10.0)
        night_engine = NightMovementEngine(min_confidence=0.80)

        subject_ref = "subject_beta_42"
        t0_ns = 1_000_000_000

        # Generate fence event
        fence_ev = fence_engine.check_subject(
            subject_ref=subject_ref,
            bbox=BoundingBox(x1=100, y1=100, x2=200, y2=200),
            camera_id="cam-01",
            timestamp_ns=t0_ns,
            source_resolution=(1000, 1000),
            zones=[restricted_vault_zone],
            confidence=0.96,
        )[0]
        fence_payload = fence_engine.build_evidence_payload(fence_ev)

        # Generate dwell event
        dwell_engine.record_zone_presence(
            subject_ref=subject_ref,
            zone_id="zone_vault",
            camera_id="cam-01",
            timestamp_ns=t0_ns,
            confidence=0.94,
            zone=restricted_vault_zone,
        )
        dwell_ev = dwell_engine.record_zone_presence(
            subject_ref=subject_ref,
            zone_id="zone_vault",
            camera_id="cam-01",
            timestamp_ns=t0_ns + 90_000_000_000,
            confidence=0.94,
            zone=restricted_vault_zone,
        )
        assert dwell_ev is not None
        dwell_payload = dwell_engine.build_evidence_payload(dwell_ev)

        # Generate night event
        night_ev = night_engine.evaluate(
            subject_ref=subject_ref,
            zone_id="zone_vault",
            camera_id="cam-01",
            timestamp_ns=t0_ns + 5_000_000_000,
            lighting_condition=LightingCondition.NIGHT_DARK,
            associated_event_type="RESTRICTED_ZONE_INTRUSION",
            event_confidence=0.91,
        )
        assert night_ev is not None
        night_payload = night_engine.build_evidence_payload(night_ev)

        # Create distinct Evidence records
        evidence_1 = Evidence(
            evidence_id="evd_fence_01",
            source_store="event_store",
            record_type="RESTRICTED_ZONE_INTRUSION",
            record_id="rec_fence_01",
            timestamp_ns=t0_ns,
            camera_id="cam-01",
            global_id=subject_ref,
            explanation=fence_ev.explanation,
            payload=fence_payload,
        )

        evidence_2 = Evidence(
            evidence_id="evd_dwell_01",
            source_store="event_store",
            record_type="LOITERING_DETECTED",
            record_id="rec_dwell_01",
            timestamp_ns=t0_ns + 90_000_000_000,
            camera_id="cam-01",
            global_id=subject_ref,
            explanation=dwell_ev.explanation,
            payload=dwell_payload,
        )

        evidence_3 = Evidence(
            evidence_id="evd_night_01",
            source_store="event_store",
            record_type="NIGHT_MOVEMENT",
            record_id="rec_night_01",
            timestamp_ns=t0_ns + 5_000_000_000,
            camera_id="cam-01",
            global_id=subject_ref,
            explanation=night_ev.explanation,
            payload=night_payload,
        )

        # Requirement I: Verify no cross-field contamination
        assert "zone_dwell_sigma" not in evidence_1.payload
        assert "lighting_condition" not in evidence_1.payload
        assert evidence_1.payload["is_restricted_zone"] is True

        assert "is_restricted_zone" not in evidence_2.payload
        assert "lighting_condition" not in evidence_2.payload
        assert "zone_dwell_sigma" in evidence_2.payload

        assert "is_restricted_zone" not in evidence_3.payload
        assert "zone_dwell_sigma" not in evidence_3.payload
        assert evidence_3.payload["lighting_condition"] == "night_dark"

        # Unique IDs
        assert len({evidence_1.evidence_id, evidence_2.evidence_id, evidence_3.evidence_id}) == 3


class TestSuspiciousActivityCoOccurrence:
    """Proves Requirements E, F, G, and multiple signal combinations."""

    def test_combination_restricted_zone_and_loitering(
        self, restricted_vault_zone: Zone
    ) -> None:
        """Combination 1: RESTRICTED_ZONE_INTRUSION + LOITERING_DETECTED -> SUSPICIOUS_ACTIVITY."""
        fence_engine = FenceEngine()
        dwell_engine = DwellEngine(default_max_dwell_s=30.0, default_std_dwell_s=10.0)
        hypo_generator = HypothesisGenerator()

        subject_ref = "subject_gamma_01"
        t0_ns = 1_000_000_000
        t1_ns = t0_ns + 100_000_000_000

        fence_ev = fence_engine.check_subject(
            subject_ref=subject_ref,
            bbox=BoundingBox(x1=150, y1=150, x2=250, y2=250),
            camera_id="cam-01",
            timestamp_ns=t0_ns,
            source_resolution=(1000, 1000),
            zones=[restricted_vault_zone],
            confidence=0.95,
        )[0]

        dwell_engine.record_zone_presence(
            subject_ref=subject_ref,
            zone_id="zone_vault",
            camera_id="cam-01",
            timestamp_ns=t0_ns,
            confidence=0.93,
            zone=restricted_vault_zone,
        )
        dwell_ev = dwell_engine.record_zone_presence(
            subject_ref=subject_ref,
            zone_id="zone_vault",
            camera_id="cam-01",
            timestamp_ns=t1_ns,
            confidence=0.93,
            zone=restricted_vault_zone,
        )
        assert dwell_ev is not None

        ev1 = Evidence(
            evidence_id="ev_f1",
            source_store="event_store",
            record_type="RESTRICTED_ZONE_INTRUSION",
            record_id="rec_f1",
            timestamp_ns=t0_ns,
            camera_id="cam-01",
            global_id=subject_ref,
            payload=fence_engine.build_evidence_payload(fence_ev),
        )

        ev2 = Evidence(
            evidence_id="ev_d1",
            source_store="event_store",
            record_type="LOITERING_DETECTED",
            record_id="rec_d1",
            timestamp_ns=t1_ns,
            camera_id="cam-01",
            global_id=subject_ref,
            payload=dwell_engine.build_evidence_payload(dwell_ev),
        )

        trees = hypo_generator.generate_trees(
            evidence_items=[ev1, ev2],
            window_start_ns=t0_ns,
            window_end_ns=t1_ns + 1_000_000,
        )

        assert len(trees) >= 1
        primary_hyp = trees[0].root_node.hypothesis

        # Requirement F: Resulting hypothesis is specifically SUSPICIOUS_ACTIVITY
        assert primary_hyp.hypothesis_type == "SUSPICIOUS_ACTIVITY"
        assert primary_hyp.primary_subject_ref == subject_ref

        # Requirement C & E: Evidence IDs link to both independent items
        assert set(primary_hyp.evidence_ids) == {"ev_f1", "ev_d1"}

        # Requirement G: Explanation identifies contributing independent signals
        exp = primary_hyp.explanation
        assert "RESTRICTED_ZONE_INTRUSION" in exp
        assert "LOITERING_DETECTED" in exp
        assert subject_ref in exp

        # Rule 8 non-causal compliance
        for term in PROHIBITED_TERMS:
            assert term not in exp.lower()

        # Child nodes at depth 2 represent the contributing signals
        children = trees[0].root_node.children
        assert len(children) == 2
        child_types = {c.hypothesis.hypothesis_type for c in children}
        assert child_types == {
            "RESTRICTED_ZONE_INTRUSION_signal",
            "LOITERING_DETECTED_signal",
        }

