class TestEvaluatorCrossEvidenceIntegration:
    """Verifies that SituationalRiskEvaluator correctly evaluates distributed evidence."""

    def test_evaluator_fires_critical_on_distributed_evidence_items(
        self, restricted_vault_zone: Zone
    ) -> None:
        """Proves that SituationalRiskEvaluator evaluates multi-factor rules across separate evidence items."""
        evaluator = SituationalRiskEvaluator()
        fence_engine = FenceEngine()
        dwell_engine = DwellEngine(default_max_dwell_s=30.0, default_std_dwell_s=10.0)

        subject_ref = "subject_distributed_crit"
        now_ns = 1_000_000_000_000
        t0_ns = now_ns - 100_000_000_000
        t1_ns = now_ns

        # 1. Fence event: provides is_restricted_zone=True
        fence_ev = fence_engine.check_subject(
            subject_ref=subject_ref,
            bbox=BoundingBox(x1=100, y1=100, x2=200, y2=200),
            camera_id="cam-01",
            timestamp_ns=t0_ns,
            source_resolution=(1000, 1000),
            zones=[restricted_vault_zone],
            confidence=0.96,
        )[0]
        ev_fence = Evidence(
            evidence_id="ev_dist_f1",
            source_store="event_store",
            record_type="RESTRICTED_ZONE_INTRUSION",
            record_id="rec_dist_f1",
            timestamp_ns=t0_ns,
            camera_id="cam-01",
            global_id=subject_ref,
            payload=fence_engine.build_evidence_payload(fence_ev),
        )

        # 2. Dwell event: provides zone_dwell_sigma > 5.0
        dwell_engine.record_zone_presence(
            subject_ref=subject_ref,
            zone_id="zone_vault",
            camera_id="cam-01",
            timestamp_ns=t0_ns,
            confidence=0.95,
            zone=restricted_vault_zone,
        )
        dwell_ev = dwell_engine.record_zone_presence(
            subject_ref=subject_ref,
            zone_id="zone_vault",
            camera_id="cam-01",
            timestamp_ns=t1_ns,
            confidence=0.95,
            zone=restricted_vault_zone,
        )
        assert dwell_ev is not None
        assert dwell_ev.zone_dwell_sigma > 5.0
        ev_dwell = Evidence(
            evidence_id="ev_dist_d1",
            source_store="event_store",
            record_type="LOITERING_DETECTED",
            record_id="rec_dist_d1",
            timestamp_ns=t1_ns,
            camera_id="cam-01",
            global_id=subject_ref,
            payload=dwell_engine.build_evidence_payload(dwell_ev),
        )

        # 3. Trajectory anomaly event: provides trajectory_anomaly_sigma > 3.5
        ev_traj = Evidence(
            evidence_id="ev_dist_t1",
            source_store="event_store",
            record_type="TRAJECTORY_ANOMALY",
            record_id="rec_dist_t1",
            timestamp_ns=t1_ns - 10_000_000_000,
            camera_id="cam-01",
            global_id=subject_ref,
            payload={
                "trajectory_anomaly_sigma": 4.1,
                "confidence": 0.94,
                "subject_ref": subject_ref,
            },
        )

        # Evaluate all 3 distinct items together
        risk_signal = evaluator.evaluate(
            evidence_items=[ev_fence, ev_dwell, ev_traj],
            system_mode=SystemMode.OPERATIONAL_MODE,
            window_start_ns=t0_ns,
            window_end_ns=t1_ns,
        )

        assert risk_signal.risk_level == "CRITICAL"
        assert risk_signal.risk_score == 1.00
        assert risk_signal.suppressed is False

        # All 3 factors present in contributing factors
        factors = set(risk_signal.contributing_factors)
        assert "restricted_zone_condition" in factors
        assert "zone_dwell_gt_5.0sigma" in factors
        assert "trajectory_anomaly_gt_3.5sigma" in factors

        # All 3 evidence IDs preserved
        assert set(risk_signal.evidence_ids) == {
            "ev_dist_f1",
            "ev_dist_d1",
            "ev_dist_t1",
        }
